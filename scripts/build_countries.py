#!/usr/bin/env python3
"""Build backend/config/countries.csv from Natural Earth (public domain).

Natural Earth's Admin 0 countries layer carries, for each country or territory, its ISO
codes, the UN geoscheme region and subregion (REGION_UN, SUBREGION), a label point that
lies inside the country, and its Wikidata ID. Natural Earth is public domain, so the
derived CSV is committed and the database seed never needs the network.

    python3 scripts/build_countries.py            # download and rebuild the CSV
    python3 scripts/build_countries.py --check    # fail if the committed CSV is stale

Rules, applied in code rather than by hand:
- ISO_A3_EH / ISO_A2_EH are used ("EH" fills codes Natural Earth leaves as -99 for
  France and Norway because of their overseas parts).
- Features with no ISO alpha-3 code at all (Somaliland, Northern Cyprus, Siachen
  Glacier, Kosovo) are left out: the countries table is keyed on ISO codes.
- When two features share a code (Australia and Ashmore and Cartier Islands), the one
  whose ADM0_A3 equals the code wins.
- Natural Earth's political classification (sovereign, dependency, disputed) is not
  copied: WorldScope does not take a position on status, it only needs codes, names,
  regions and a point to place country-level items on the map.
"""

from __future__ import annotations

import csv
import io
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "backend" / "config" / "countries.csv"
SOURCE_URL = (
    "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/"
    "v5.1.2/geojson/ne_50m_admin_0_countries.geojson"
)
FIELDS = [
    "iso3",
    "iso2",
    "name",
    "name_long",
    "region",
    "subregion",
    "label_lat",
    "label_lon",
    "wikidata_qid",
]
def _code(value: object) -> str | None:
    text = str(value or "").strip()
    return None if text in ("", "-99") else text


def build(geojson: dict[str, object]) -> list[dict[str, str]]:
    features = geojson["features"]
    assert isinstance(features, list)
    chosen: dict[str, dict[str, object]] = {}
    for feature in features:
        props = feature["properties"]
        iso3 = _code(props.get("ISO_A3_EH"))
        if iso3 is None:
            continue
        current = chosen.get(iso3)
        if current is None or props.get("ADM0_A3") == iso3:
            chosen[iso3] = props

    rows = []
    for iso3, props in sorted(chosen.items()):
        rows.append(
            {
                "iso3": iso3,
                "iso2": _code(props.get("ISO_A2_EH")) or "",
                "name": str(props["NAME"]),
                "name_long": str(props.get("NAME_LONG") or props["NAME"]),
                "region": str(props["REGION_UN"]),
                "subregion": str(props["SUBREGION"]),
                "label_lat": f"{float(props['LABEL_Y']):.4f}",
                "label_lon": f"{float(props['LABEL_X']):.4f}",
                "wikidata_qid": _code(props.get("WIKIDATAID")) or "",
            }
        )
    return rows


def render(rows: list[dict[str, str]]) -> str:
    out = io.StringIO()
    out.write(f"# Generated by scripts/build_countries.py from {SOURCE_URL}\n")
    out.write("# Natural Earth data is in the public domain. Do not edit by hand.\n")
    writer = csv.DictWriter(out, fieldnames=FIELDS, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return out.getvalue()


def main() -> int:
    with urllib.request.urlopen(SOURCE_URL, timeout=60) as response:  # noqa: S310 (fixed https URL)
        geojson = json.load(response)
    text = render(build(geojson))
    if "--check" in sys.argv:
        if TARGET.read_text() != text:
            print(f"{TARGET} is out of date; run scripts/build_countries.py")
            return 1
        print(f"{TARGET} is up to date.")
        return 0
    TARGET.write_text(text)
    print(f"Wrote {TARGET} ({text.count(chr(10)) - 3} countries and territories).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
